[CmdletBinding()]
param(
    [string]$SourceDirectory = (Join-Path $PSScriptRoot '../.reference/solstice'),
    [string]$Commit = '1d7808f52ef4ba6e34a7fbcc65294907a7761611',
    [string]$ProjectDirectory = (Join-Path $PSScriptRoot '..')
)

$ErrorActionPreference = 'Stop'
$sourceRoot = (Resolve-Path -LiteralPath $SourceDirectory).Path
$projectRoot = (Resolve-Path -LiteralPath $ProjectDirectory).Path
$sourcePath = 'src/SDK/SigManager.hpp'
$repository = 'https://github.com/surukotonai/solstice'
$resolvedCommit = (& git -C $sourceRoot rev-parse --verify "${Commit}^{commit}" | Out-String).Trim()
if ($LASTEXITCODE -ne 0 -or $resolvedCommit -notmatch '^[0-9a-f]{40}$') {
    throw 'The requested Solstice commit is not available in the local checkout.'
}
$sourceText = (& git -C $sourceRoot show "${resolvedCommit}:$sourcePath" | Out-String)
if ($LASTEXITCODE -ne 0) { throw "Cannot read $sourcePath at $resolvedCommit" }

# Remove block comments while preserving line numbers. This also handles
# /**/DEFINE_SIG(...) and ignores all signatures inside a /* ... */ block.
$uncommented = [regex]::Replace($sourceText, '/\*[\s\S]*?\*/', {
    param($match)
    return [regex]::Replace($match.Value, '[^\r\n]', ' ')
})
$originalLines = $sourceText -split '\r?\n'
$lines = $uncommented -split '\r?\n'
$signatures = [System.Collections.Generic.List[object]]::new()
$names = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
$expression = '^\s*DEFINE_SIG\(\s*(?<name>\w+)\s*,\s*"(?<pattern>[^"]+)"\s*,\s*SigType::(?<kind>Sig|RefSig)\s*,\s*(?<offset>\d+)\s*\)\s*;'
for ($index = 0; $index -lt $lines.Length; $index++) {
    $line = $lines[$index] -replace '//.*$', ''
    if ($line -notmatch $expression) { continue }
    $name = $Matches.name
    $pattern = $Matches.pattern.Trim()
    $kind = $Matches.kind
    $offset = [int]$Matches.offset
    if (-not $names.Add($name)) { throw "Duplicate signature: $name" }
    $literalCount = 0
    foreach ($token in ($pattern -split '\s+')) {
        if ($token -match '^[0-9a-fA-F]{2}$') { $literalCount++; continue }
        if ($token -notin @('?', '??')) { throw "Invalid token '$token' in $name" }
    }
    if ($literalCount -eq 0) { throw "No literal bytes in $name" }
    if ($kind -eq 'Sig' -and $offset -ne 0) {
        throw "Direct signature $name has nonzero offset; review upstream semantics before import."
    }
    $comment = ''
    $commentIndex = $originalLines[$index].IndexOf('//')
    if ($commentIndex -ge 0) { $comment = $originalLines[$index].Substring($commentIndex + 2).Trim() }
    $versionHint = ''
    if ($comment -match '(?<!\d)\d{1,2}(?:\.\d{1,2}){1,2}') { $versionHint = $Matches[0] }
    $signatures.Add([ordered]@{
        name = $name
        pattern = $pattern
        resolution = $(if ($kind -eq 'RefSig') { 'relative32' } else { 'direct' })
        displacement_offset = $offset
        source_line = $index + 1
        upstream_version_hint = $versionHint
        upstream_uncertain = [bool]($comment -match '(?i)maybe|guess|need check|check later|check latter')
    })
}
if ($signatures.Count -eq 0) { throw 'No active DEFINE_SIG entries were found.' }

# Dependency licenses in include/ do not license SigManager.hpp itself.
$rootFiles = & git -C $sourceRoot ls-tree --name-only $resolvedCommit
if ($LASTEXITCODE -ne 0) { throw 'Cannot inspect upstream root files.' }
$hasRootLicense = @($rootFiles | Where-Object { $_ -match '^(?i:LICENSE|LICENCE|COPYING)(\..*)?$' }).Count -gt 0
$licenseStatus = if ($hasRootLicense) { 'root_license_present_review_required' } else { 'no_root_license_found' }
$manifest = [ordered]@{
    schema_version = 1
    source = [ordered]@{
        repository = $repository
        commit = $resolvedCommit
        path = $sourcePath
        blob_url = "$repository/blob/$resolvedCommit/$sourcePath"
        license_status = $licenseStatus
    }
    compatibility = 'Unverified against a running Minecraft build. Upstream version comments are hints only.'
    signatures = @($signatures.ToArray())
}
$manifestPath = Join-Path $projectRoot 'data/signatures/solstice.json'
$catalogPath = Join-Path $projectRoot 'src/memory/solstice_catalog.inc'
New-Item -ItemType Directory -Force -Path (Split-Path $manifestPath), (Split-Path $catalogPath) | Out-Null
$encoding = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($manifestPath, ($manifest | ConvertTo-Json -Depth 8) + "`n", $encoding)

$catalog = [System.Collections.Generic.List[string]]::new()
$catalog.Add('// Generated by tools/import-solstice-signatures.ps1. Do not edit manually.')
$catalog.Add("// Source: $repository/blob/$resolvedCommit/$sourcePath")
$catalog.Add('// Pattern data only. No upstream SDK or scanner implementation is copied.')
$catalog.Add('constexpr SignatureSource source{')
$catalog.Add("    `"$repository`", `"$resolvedCommit`", `"$sourcePath`", `"$licenseStatus`"};")
$catalog.Add('constexpr SignatureDefinition definitions[]{')
foreach ($signature in $signatures) {
    $uncertain = if ($signature.upstream_uncertain) { 'true' } else { 'false' }
    $catalog.Add("    {`"$($signature.name)`", `"$($signature.pattern)`", SignatureResolution::$($signature.resolution), $($signature.displacement_offset), $($signature.source_line), `"$($signature.upstream_version_hint)`", $uncertain},")
}
$catalog.Add('};')
[System.IO.File]::WriteAllText($catalogPath, ($catalog -join "`n") + "`n", $encoding)
Write-Output "Imported $($signatures.Count) signatures from $resolvedCommit"
