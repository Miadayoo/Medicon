import { createPublicKey, generateKeyPairSync, randomBytes, type KeyObject } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { parseArgs, parseEnv } from 'node:util'
import { ROOT_DIR } from '../src/config.ts'
import { loadSigningKey } from '../src/services/releases.ts'

// Matches MEDICON_UPDATE_HOST in CMakeLists.txt. An existing URL wins unless
// --base-url is explicitly supplied; request headers never choose this host.
const DEFAULT_BASE_URL = 'https://medicon.auau1000.com'

export function publicKeyHeader(key: KeyObject): string {
  const jwk = createPublicKey(key).export({ format: 'jwk' })
  const array = (name: string, encoded: string | undefined): string => {
    const bytes = Buffer.from(encoded ?? '', 'base64url')
    const lines: string[] = []
    for (let i = 0; i < bytes.length; i += 16)
      lines.push('    ' + [...bytes.subarray(i, i + 16)].map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ') + ',')
    return `inline constexpr std::array<std::uint8_t, ${bytes.length}> ${name}{\n${lines.join('\n')}\n};`
  }
  return `#pragma once

#include <array>
#include <cstdint>

// Generated by the server release tools. Public half only; keep the private key on the server.
namespace medicon::update {

${array('release_key_modulus', jwk.n)}
${array('release_key_exponent', jwk.e)}

} // namespace medicon::update
`
}

function setEnvValue(text: string, name: string, value: string): string {
  const line = `${name}="${value}"`
  const pattern = new RegExp(`^[ \\t]*(?:export[ \\t]+)?${name}[ \\t]*=.*$`, 'gm')
  return pattern.test(text) ? text.replace(pattern, () => line) : text.trimEnd() + '\n' + line + '\n'
}

// Explicit first-time setup, never an automatic key rotation on server startup.
// It also works with only social-server/ deployed, without the C++ source tree.
export function setupReleases(root: string, baseUrl?: string) {
  const envPath = resolve(root, '.env')
  let text = readFileSync(existsSync(envPath) ? envPath : resolve(root, '.env.example'), 'utf8').replace(/^\uFEFF/, '')
  const env = parseEnv(text)
  const publicBaseUrl = (baseUrl ?? (env.PUBLIC_BASE_URL?.trim() || DEFAULT_BASE_URL)).replace(/\/+$/, '')
  if (!/^https:\/\/[a-z0-9.-]+(:\d{1,5})?$/i.test(publicBaseUrl))
    throw new Error('--base-url は https://host の形にしてください（パスなし）')

  const configuredKey = env.RELEASE_SIGNING_KEY?.trim()
  const keySetting = configuredKey || 'keys/release-private.pem'
  const keyPath = resolve(root, keySetting)
  const sourceHeader = resolve(root, '../include/medicon/update/ReleasePublicKey.hpp')
  const headerPath = existsSync(dirname(sourceHeader)) ? sourceHeader : resolve(root, 'keys/ReleasePublicKey.hpp')
  const releasesDir = resolve(root, env.RELEASES_DIR?.trim() || 'releases')
  if (!existsSync(keyPath)) {
    if (configuredKey || existsSync(resolve(releasesDir, 'latest')) ||
        (existsSync(headerPath) && !readFileSync(headerPath, 'utf8').includes('array<std::uint8_t, 0>')))
      throw new Error('既存の署名鍵が見つかりません。元の release-private.pem を戻してください（鍵を変えると既存の Loader が更新を検証できません）')
    const { privateKey } = generateKeyPairSync('rsa', { modulusLength: 3072, publicExponent: 65537 })
    mkdirSync(dirname(keyPath), { recursive: true })
    writeFileSync(keyPath, privateKey.export({ type: 'pkcs8', format: 'pem' }), { flag: 'wx', mode: 0o600 })
  }
  const key = loadSigningKey(keyPath)
  mkdirSync(dirname(headerPath), { recursive: true })
  writeFileSync(headerPath, publicKeyHeader(key))
  mkdirSync(releasesDir, { recursive: true })

  if (!env.ADMIN_SECRET?.trim()) text = setEnvValue(text, 'ADMIN_SECRET', randomBytes(32).toString('base64url'))
  text = setEnvValue(text, 'RELEASE_SIGNING_KEY', keySetting.replaceAll('\\', '/'))
  text = setEnvValue(text, 'PUBLIC_BASE_URL', publicBaseUrl)
  writeFileSync(envPath, text, { mode: 0o600 })
  return { keyPath, headerPath, publicBaseUrl, releasesDir }
}

if (import.meta.main) {
  try {
    const { values } = parseArgs({ options: { 'base-url': { type: 'string' } } })
    const result = setupReleases(ROOT_DIR, values['base-url'])
    console.log(`DLL 公開の設定が完了しました: ${result.publicBaseUrl}`)
    console.log(`秘密鍵（既存の鍵は再利用）: ${result.keyPath}`)
    console.log(`公開鍵ヘッダー: ${result.headerPath}`)
    console.log(`DLL 保存先: ${result.releasesDir}/<version>/MediconCore.dll`)
    console.log('サーバーを再起動してください。初回はこの公開鍵ヘッダーで MediconLoader をビルドし直して配布してください。')
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err))
    process.exitCode = 1
  }
}
